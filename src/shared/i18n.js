function detectBrowserLanguage() {
  const browserLang = globalThis.chrome?.i18n?.getUILanguage?.()
    || globalThis.browser?.i18n?.getUILanguage?.()
    || globalThis.navigator?.language
    || 'en';
  if (/zh[-_]?(?:tw|hk|mo|hant)\b/i.test(browserLang)) return 'zh-TW';
  if (/^zh\b/i.test(browserLang)) return 'zh-CN';
  return 'en';
}

export function resolveLanguage(preference) {
  if (SUPPORTED_LANGUAGES.includes(preference)) return preference;
  return detectBrowserLanguage();
}

export function themeDisplayName(id, language, fallback) {
  const locale = resolveLanguage(language);
  return THEME_NAMES[locale]?.[id] || THEME_NAMES.en[id] || fallback || id;
}

export function languageOptionLabelKey(value) {
  if (value === 'zh-CN') return 'languageChinese';
  if (value === 'zh-TW') return 'languageChineseTraditional';
  return 'languageEnglish';
}

export function translate(language, key, vars = {}) {
  let text = messages[language]?.[key] ?? messages.en[key] ?? key;
  for (const [name, value] of Object.entries(vars)) {
    text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}

export function applyTranslations(root, language) {
  const doc = root.documentElement ? root : document;
  const owner = root.documentElement ? root : document;
  owner.documentElement.lang = SUPPORTED_LANGUAGES.includes(language) ? language : 'en';
  for (const element of doc.querySelectorAll('[data-i18n]')) {
    element.textContent = translate(language, element.dataset.i18n);
  }
  for (const element of doc.querySelectorAll('[data-i18n-aria]')) {
    element.setAttribute('aria-label', translate(language, element.dataset.i18nAria));
  }
  for (const element of doc.querySelectorAll('[data-i18n-title]')) {
    element.setAttribute('title', translate(language, element.dataset.i18nTitle));
  }
  for (const element of doc.querySelectorAll('[data-i18n-placeholder]')) {
    element.setAttribute('placeholder', translate(language, element.dataset.i18nPlaceholder));
  }
}

export function listMissingKeys() {
  const enKeys = Object.keys(messages.en);
  const compare = (locale) => {
    const keys = Object.keys(messages[locale] || {});
    return {
      missing: enKeys.filter((key) => !(key in (messages[locale] || {}))),
      extra: keys.filter((key) => !(key in messages.en))
    };
  };
  const zh = compare('zh-CN');
  const tw = compare('zh-TW');
  return {
    missingInZh: zh.missing,
    missingInEn: zh.extra,
    missingInZhTW: tw.missing,
    extraInZhTW: tw.extra
  };
}

